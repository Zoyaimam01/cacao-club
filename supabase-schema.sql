-- Cacao Club Supabase schema
-- Run this complete script in Supabase SQL Editor.
-- Browser code must use only the anon/public key, never service_role.

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now()
);
alter table public.newsletter_subscribers enable row level security;
drop policy if exists "Anyone can subscribe to newsletter" on public.newsletter_subscribers;
create policy "Anyone can subscribe to newsletter" on public.newsletter_subscribers
for insert to anon, authenticated
with check (char_length(email) <= 320 and position('@' in email) > 1);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles for select to authenticated using (auth.uid() = id);
drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

-- Keep order headers and line items in separate tables.
-- user_id is optional to allow demo orders and guest checkouts.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  status text not null default 'placed' check (status in ('placed','processing','shipped','delivered','cancelled')),
  customer_first_name text not null,
  customer_last_name text not null,
  customer_email text not null,
  shipping_address text not null,
  shipping_city text not null,
  shipping_region text not null,
  shipping_postal_code text not null,
  shipping_country text not null,
  notes text not null default '',
  subtotal numeric(10,2) not null check (subtotal >= 0),
  created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
drop policy if exists "Users can view own orders" on public.orders;
create policy "Users can view own orders" on public.orders for select to authenticated using (auth.uid() = user_id);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint not null,
  product_name text not null,
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(10,2) generated always as (unit_price * quantity) stored
);
alter table public.order_items enable row level security;
drop policy if exists "Users can view own order items" on public.order_items;
create policy "Users can view own order items" on public.order_items for select to authenticated
using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));

-- Create the profile automatically from Supabase Auth metadata on signup.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name',''), new.email)
  on conflict (id) do update set full_name = excluded.full_name, email = excluded.email;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Order creation is one database transaction. The browser cannot set user_id or trusted totals.
-- Works for logged-in users, demo accounts, and guest checkout.
create or replace function public.place_order(order_payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_customer jsonb := order_payload -> 'customer';
  v_items jsonb := order_payload -> 'items';
  v_order_id bigint;
  v_subtotal numeric(10,2) := 0;
  v_item jsonb;
  v_price numeric(10,2);
  v_quantity integer;
  v_name text;
  v_product_id bigint;
begin
  if v_customer is null or v_items is null or jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) = 0 then
    raise exception 'Customer and order item details are required.';
  end if;
  if length(coalesce(v_customer->>'first_name','')) = 0
     or length(coalesce(v_customer->>'last_name','')) = 0
     or position('@' in coalesce(v_customer->>'email','')) < 2
     or length(coalesce(v_customer->>'address','')) = 0
     or length(coalesce(v_customer->>'city','')) = 0
     or length(coalesce(v_customer->>'postal_code','')) = 0
     or length(coalesce(v_customer->>'country','')) = 0 then
    raise exception 'Please complete all required delivery details.';
  end if;
  -- Recalculate totals on the server using an allowlisted catalogue.
  for v_item in select value from jsonb_array_elements(v_items)
  loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_quantity := (v_item->>'quantity')::integer;
    if v_quantity < 1 or v_quantity > 50 then raise exception 'Invalid item quantity.'; end if;
    case v_product_id
      when 1 then v_price:=8.50; v_name:='72% Dark Chocolate Bar with Raspberry';
      when 2 then v_price:=11.00; v_name:='72% Dark Chocolate Clusters with Raspberry';
      when 3 then v_price:=5.50; v_name:='Mini 72% Dark Chocolate Bar with Raspberry';
      when 4 then v_price:=8.00; v_name:='Sea Salt Crunch Chocolate Bar';
      when 5 then v_price:=10.00; v_name:='Milk Chocolate Hazelnut Bites';
      when 6 then v_price:=28.00; v_name:='The Daily Pause Gift Box';
      when 7 then v_price:=8.50; v_name:='Salted Caramel Chocolate Bar';
      when 8 then v_price:=34.00; v_name:='Chocolate Discovery Box';
      else raise exception 'Unknown product in order.';
    end case;
    v_subtotal := v_subtotal + v_price * v_quantity;
  end loop;
  insert into public.orders (
    user_id, customer_first_name, customer_last_name, customer_email,
    shipping_address, shipping_city, shipping_region, shipping_postal_code,
    shipping_country, notes, subtotal
  ) values (
    v_user_id, v_customer->>'first_name', v_customer->>'last_name', v_customer->>'email',
    v_customer->>'address', v_customer->>'city', coalesce(v_customer->>'region',''),
    v_customer->>'postal_code', v_customer->>'country', coalesce(v_customer->>'notes',''), v_subtotal
  ) returning id into v_order_id;
  for v_item in select value from jsonb_array_elements(v_items)
  loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_quantity := (v_item->>'quantity')::integer;
    case v_product_id
      when 1 then v_price:=8.50; v_name:='72% Dark Chocolate Bar with Raspberry';
      when 2 then v_price:=11.00; v_name:='72% Dark Chocolate Clusters with Raspberry';
      when 3 then v_price:=5.50; v_name:='Mini 72% Dark Chocolate Bar with Raspberry';
      when 4 then v_price:=8.00; v_name:='Sea Salt Crunch Chocolate Bar';
      when 5 then v_price:=10.00; v_name:='Milk Chocolate Hazelnut Bites';
      when 6 then v_price:=28.00; v_name:='The Daily Pause Gift Box';
      when 7 then v_price:=8.50; v_name:='Salted Caramel Chocolate Bar';
      when 8 then v_price:=34.00; v_name:='Chocolate Discovery Box';
    end case;
    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
    values (v_order_id, v_product_id, v_name, v_price, v_quantity);
  end loop;
  return v_order_id;
end;
$$;
grant execute on function public.place_order(jsonb) to anon, authenticated;

-- Optional product catalogue table for future admin-managed inventory.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  category text not null check (category in ('bars','bites','gift')),
  price numeric(10,2) not null check (price >= 0),
  weight text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.products enable row level security;
drop policy if exists "Visitors can read active products" on public.products;
create policy "Visitors can read active products" on public.products for select to anon, authenticated using (active = true);
